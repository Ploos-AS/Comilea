#[must_use]
pub fn opcode_info(opcode: u8) -> OpcodeInfo {
    let class = if JAM.contains(&opcode) { OpcodeClass::Jam } else if OFFICIAL.contains(&opcode) { OpcodeClass::Official } else { OpcodeClass::Undocumented };
    OpcodeInfo { opcode, class, implemented: IMPLEMENTED.contains(&opcode) }
}

#[cfg(test)]
mod tests {
    use super::{opcode_info, OpcodeClass, OFFICIAL, OFFICIAL_OPCODE_COUNT};
    #[test]
    fn official_table_is_complete_and_unique() {
        assert_eq!(OFFICIAL.len(), OFFICIAL_OPCODE_COUNT);
        let mut seen = [false; 256];
        for opcode in OFFICIAL {
            assert!(!seen[usize::from(opcode)], "duplicate opcode {opcode:02x}");
            seen[usize::from(opcode)] = true;
            assert_eq!(opcode_info(opcode).class, OpcodeClass::Official);
        }
    }
}
